type RawSourceTuple = [
  id: string,
  name: string,
  shortName: string,
  domain: string,
  url: string,
  category: SourceCategory,
  stageLabelAr: string,
  summaryAr: string,
  howToApplyAr: string,
  keyTopics: string[],
  isCore16?: boolean,
];

const CATEGORY_AR: Record<SourceCategory, string> = {
  standards: 'المعايير والشهادات الدولية',
  materials: 'الأقمشة والألياف والمواد',
  trends: 'الاتجاهات والإلهام البصري',
  cad: 'التصميم الرقمي و3D والباترون',
  sourcing: 'منصات التوريد والمصانع',
  machinery: 'ماكينات النسيج والخياطة والقص',
  printing: 'الطباعة الرقمية والتطريز والحرارة',
  trims: 'الإكسسوارات والسحابات والخيوط',
  egypt: 'منظومة مصر والهيئات والمصانع',
  benchmarks: 'الشركات والعلامات العالمية',
  designers: 'رواد التصميم والفكر الإبداعي',
};

function buildSources(rows: RawSourceTuple[]): TextileSource[] {
  return rows.map(
    ([
      id,
      name,
      shortName,
      domain,
      url,
      category,
      stageLabelAr,
      summaryAr,
      howToApplyAr,
      keyTopics,
      isCore16,
    ]) => ({
      id,
      name,
      shortName,
      domain,
      url,
      category,
      categoryLabelAr: CATEGORY_AR[category],
      stageLabelAr,
      summaryAr,
      howToApplyAr,
      keyTopics,
      isCore16: Boolean(isCore16),
      samplePromptAr:
        category === 'designers'
          ? `ما الفلسفة التصميمية وبصمة ${name} في بناء الهوية والقصّات، وكيف أستلهم منها في تطوير براند ملابس عصري؟`
          : category === 'benchmarks'
            ? `حلّل نموذج عمل وسلاسل إمداد ${name}، وما الدروس العملية التي يمكن لبراند ناشئ تطبيقها في التسعير والتوسع؟`
            : `كيف أستفيد عملياً من ${name} (${stageLabelAr}) في تطوير براند الملابس ورفع الجودة أو تقليل التكلفة؟`,
    })
  );
}

